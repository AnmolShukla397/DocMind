import { expect, test } from '@playwright/test'

test('3D source story moves continuously without changing canvas layout', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const scene=page.locator('.dv-stage')
  const canvas=scene.locator('canvas')
  await expect(canvas).toBeVisible()
  expect(await page.locator('.dv-cursor').evaluate(element=>getComputedStyle(element).opacity)).toBe('0')
  await page.waitForTimeout(500)
  const first=await canvas.screenshot({path:'test-results/08-hero-frame-a.png'})
  await page.waitForTimeout(900)
  const second=await canvas.screenshot({path:'test-results/09-hero-frame-b.png'})
  expect(first.equals(second)).toBe(false)
  const firstWidth=(await scene.boundingBox())!.width
  const originalCanvas=await canvas.evaluate(element=>{(window as Window & {__sceneCanvas?:Element}).__sceneCanvas=element;return element.width})
  await page.evaluate(()=>window.scrollTo(0,320))
  await page.waitForTimeout(300)
  expect((await scene.boundingBox())!.width).toBeCloseTo(firstWidth,1)
  expect(await canvas.evaluate((element,width)=>element===(window as Window & {__sceneCanvas?:Element}).__sceneCanvas&&element.width===width,originalCanvas)).toBe(true)
  await page.screenshot({path:'test-results/06-hero-scroll.png'})
  for (const position of [480, 800, 1120, 1440]) {
    await page.evaluate(y=>window.scrollTo(0,y),position)
    await page.waitForTimeout(100)
    expect(await canvas.evaluate(element=>element===(window as Window & {__sceneCanvas?:Element}).__sceneCanvas)).toBe(true)
    await expect(canvas).toBeVisible()
  }
  await page.getByRole('button',{name:'Show featured source 2'}).click()
  await expect(page.getByRole('button',{name:'Show featured source 2'})).toHaveAttribute('aria-pressed','true')

  const collect=page.getByRole('tab',{name:/Collect/})
  await collect.scrollIntoViewIfNeeded()
  const width=(await collect.boundingBox())!.width
  await collect.hover()
  await page.waitForTimeout(240)
  expect((await collect.boundingBox())!.width).toBeCloseTo(width,1)
  await page.screenshot({path:'test-results/07-collect-hover.png'})
  await page.getByRole('tab',{name:/Trace/}).click()
  await expect(page.getByRole('tab',{name:/Trace/})).toHaveAttribute('aria-selected','true')
  await expect(page.getByText('A finding stays attached to its supporting passage and original page.')).toBeVisible()
})

test('mobile story fits the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const title=page.getByRole('heading',{level:1})
  await expect(title).toBeVisible()
  const bounds=await title.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x+bounds!.width).toBeLessThanOrEqual(390)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBe(0)
  await page.setViewportSize({ width: 320, height: 700 })
  const method=page.locator('.dv-process-list button').last()
  const name=await method.locator('span').boundingBox()
  const description=await method.locator('small').boundingBox()
  expect(description!.y).toBeGreaterThanOrEqual(name!.y+name!.height-1)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBe(0)
})

test('reduced motion keeps a still archive available', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const canvas=page.locator('.dv-scene canvas')
  await expect(canvas).toBeVisible()
  await page.waitForTimeout(1000)
  const first=await canvas.screenshot()
  await page.waitForTimeout(400)
  expect((await canvas.screenshot()).equals(first)).toBe(true)
})
